/** Extracts classes.jar from an AAR so a plain JVM build can use it. */
abstract class AarClassesJar : TransformAction<TransformParameters.None> {
    @get:InputArtifact
    abstract val aar: Provider<FileSystemLocation>

    override fun transform(outputs: TransformOutputs) {
        val input = aar.get().asFile
        val output = outputs.file(input.nameWithoutExtension + ".jar")
        ZipInputStream(input.inputStream().buffered()).use { zip ->
            while (true) {
                val entry = zip.nextEntry ?: break
                if (entry.name == "classes.jar") {
                    output.outputStream().use { zip.copyTo(it) }
                    return
                }
            }
        }
        error("$input has no classes.jar")
    }
}

/**
 * Builds the equivalent of AGP's mockable android.jar from Robolectric's android-all:
 * every framework method throws "Method ... not mocked.", constructors only call super,
 * and static initialisers are emptied. A test that accidentally relies on real Android
 * behaviour therefore fails here just as it would under `./gradlew :app:testDebugUnitTest`.
 */
abstract class MockableAndroidJar : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val androidAllJar: ConfigurableFileCollection

    @get:OutputFile
    abstract val outputJar: RegularFileProperty

    @TaskAction
    fun generate() {
        ZipInputStream(androidAllJar.singleFile.inputStream().buffered()).use { input ->
            ZipOutputStream(outputJar.get().asFile.outputStream().buffered()).use { output ->
                while (true) {
                    val entry = input.nextEntry ?: break
                    if (!entry.name.startsWith("android/") || !entry.name.endsWith(".class")) continue
                    output.putNextEntry(ZipEntry(entry.name))
                    output.write(mockable(input.readBytes()))
                    output.closeEntry()
                }
            }
        }
    }

    private fun mockable(classBytes: ByteArray): ByteArray {
        val node = ClassNode()
        ClassReader(classBytes).accept(node, 0)
        node.access = node.access and Opcodes.ACC_FINAL.inv()
        for (method in node.methods) {
            method.access = method.access and (Opcodes.ACC_FINAL or Opcodes.ACC_NATIVE).inv()
            if (method.access and Opcodes.ACC_ABSTRACT != 0) continue
            method.tryCatchBlocks.clear()
            method.localVariables = null
            method.instructions = when (method.name) {
                "<clinit>" -> InsnList().apply { add(InsnNode(Opcodes.RETURN)) }
                "<init>" -> {
                    // The SDK stubs let same-package test doubles (e.g. android.net.FakeUri) subclass.
                    method.access = method.access and Opcodes.ACC_PRIVATE.inv()
                    superCallOnly(node, method.instructions)
                }
                else -> throwNotMocked("Method ${method.name} in ${node.name.replace('/', '.')} not mocked.")
            }
        }
        return ClassWriter(ClassWriter.COMPUTE_MAXS).also(node::accept).toByteArray()
    }

    /**
     * Rebuilds a constructor as `super(default args...); return`, the shape SDK stub
     * constructors have. The chained call is the first `invokespecial <init>` on this class
     * or its superclass; earlier ones may construct arguments, so they cannot be kept as-is.
     */
    private fun superCallOnly(node: ClassNode, original: InsnList): InsnList {
        val chained = original.toArray().filterIsInstance<MethodInsnNode>().first {
            it.opcode == Opcodes.INVOKESPECIAL && it.name == "<init>" && (it.owner == node.superName || it.owner == node.name)
        }
        return InsnList().apply {
            add(VarInsnNode(Opcodes.ALOAD, 0))
            Type.getArgumentTypes(chained.desc).forEach { add(defaultValue(it)) }
            add(MethodInsnNode(Opcodes.INVOKESPECIAL, chained.owner, "<init>", chained.desc, false))
            add(InsnNode(Opcodes.RETURN))
        }
    }

    private fun defaultValue(type: Type): AbstractInsnNode = when (type.sort) {
        Type.OBJECT, Type.ARRAY -> InsnNode(Opcodes.ACONST_NULL)
        Type.LONG -> InsnNode(Opcodes.LCONST_0)
        Type.FLOAT -> InsnNode(Opcodes.FCONST_0)
        Type.DOUBLE -> InsnNode(Opcodes.DCONST_0)
        else -> InsnNode(Opcodes.ICONST_0)
    }

    private fun throwNotMocked(message: String) = InsnList().apply {
        add(TypeInsnNode(Opcodes.NEW, "java/lang/RuntimeException"))
        add(InsnNode(Opcodes.DUP))
        add(LdcInsnNode(message))
        add(MethodInsnNode(Opcodes.INVOKESPECIAL, "java/lang/RuntimeException", "<init>", "(Ljava/lang/String;)V", false))
        add(InsnNode(Opcodes.ATHROW))
    }
}

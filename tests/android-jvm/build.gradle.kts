// AGP generates BuildConfig; the harness generates the same fields. API_BASE_URL points at
// a reserved .test host that can never resolve, so a request the test did not route to
// its fake backend fails instead of reaching a real server.
val generateBuildConfig = tasks.register("generateBuildConfig") {
    val outputDir = layout.buildDirectory.dir("generated/buildConfig")
    // buildConfigField("String", "BUILD_MARKER", "\"value\"") in app/build.gradle.kts
    val buildMarker = Regex("""BUILD_MARKER",\s*"\\"([^\\"]+)\\""""").find(appBuildScript)?.groupValues?.get(1)
        ?: error("BUILD_MARKER not found in app/build.gradle.kts")
    inputs.property("buildMarker", buildMarker)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().file("io/bemylens/app/BuildConfig.java").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            package io.bemylens.app;

            /** Generated by tests/android-jvm (AGP generates the real one). */
            public final class BuildConfig {
              public static final boolean DEBUG = true;
              public static final String APPLICATION_ID = "io.bemylens.app";
              public static final String BUILD_TYPE = "debug";
              public static final String API_BASE_URL = "http://backend.be-my-lens.test/";
              public static final String BUILD_MARKER = "$buildMarker";
            }
            """.trimIndent() + "\n",
        )
    }
}

// AGP compiles resources with aapt2 and generates R. The harness generates R.string from
// the app's strings.xml instead (R.string is the only resource type the sources under test
// use). src/robolectricTest serves the real string values for these IDs through its test
// Application, so code calling getString() gets the app's actual text.
val stringsXml = appDir.resolve("src/main/res/values/strings.xml")
val generateR = tasks.register("generateR") {
    val outputDir = layout.buildDirectory.dir("generated/r")
    inputs.file(stringsXml)
    outputs.dir(outputDir)
    doLast {
        val names = Regex("""<string\s+name="([A-Za-z0-9_]+)"""").findAll(stringsXml.readText()).map { it.groupValues[1] }.toList()
        check(names.isNotEmpty()) { "no <string> entries found in $stringsXml" }
        val fields = names.mapIndexed { index, name ->
            "    public static final int $name = 0x${"%08x".format(0x7f100000 + index)};"
        }
        val file = outputDir.get().file("io/bemylens/app/R.java").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "package io.bemylens.app;\n\n" +
                "/** Generated by tests/android-jvm from app/src/main/res/values/strings.xml. */\n" +
                "public final class R {\n  public static final class string {\n" +
                fields.joinToString("\n") { "  $it" } +
                "\n  }\n}\n",
        )
    }
}


// Failures and skips are always printed, plus one summary line per test task.
// `-PverboseTests` also lists every passing test. Configured for Gradle's lifecycle and
// warn levels alike, so `gradle --warn` (used by run-tests.sh) still shows failures.
val verboseTests = providers.gradleProperty("verboseTests").isPresent
tasks.withType<Test>().configureEach {
    testLogging {
        val logged = if (verboseTests) arrayOf("passed", "skipped", "failed") else arrayOf("skipped", "failed")
        events(*logged)
        exceptionFormat = TestExceptionFormat.FULL
        warn {
            events(*logged)
            exceptionFormat = TestExceptionFormat.FULL
        }
    }
    val taskName = name
    addTestListener(
        object : TestListener {
            override fun beforeSuite(suite: TestDescriptor) = Unit
            override fun beforeTest(testDescriptor: TestDescriptor) = Unit
            override fun afterTest(testDescriptor: TestDescriptor, result: TestResult) = Unit
            override fun afterSuite(suite: TestDescriptor, result: TestResult) {
                if (suite.parent == null) {
                    println(
                        "$taskName: ${result.testCount} tests, ${result.successfulTestCount} passed, " +
                            "${result.failedTestCount} failed, ${result.skippedTestCount} skipped",
                    )
                }
            }
        },
    )
}


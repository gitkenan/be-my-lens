/** The version app/build.gradle.kts declares for a module, so both builds stay in step. */
fun appVersion(module: String): String =
    Regex("\"${Regex.escape(module)}:([^\"]+)\"").find(appBuildScript)?.groupValues?.get(1)
        ?: error("$module is not declared in app/build.gradle.kts")

fun appDependency(module: String): String = "$module:${appVersion(module)}"

